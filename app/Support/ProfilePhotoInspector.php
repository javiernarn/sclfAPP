<?php

namespace App\Support;

/**
 * Server-side half of the formal profile-photo check.
 *
 * The browser does the face/pose checks (PHP has no face detector); this class
 * repeats everything that needs only pixels or the file itself, so the rules
 * hold even if someone calls the API directly:
 *
 *   - readable JPEG / PNG / WebP, at least `min_side` px on the short side
 *   - no AI-generation markers, and no retouching-app names, in the file's metadata
 *   - sharp (not blurry) in the centre of the picture
 *   - plain, light, colourless background along the top and sides
 *
 * About AI detection: there is no reliable way to tell an AI image from its
 * pixels. This only finds the markers AI tools write into a file (IPTC
 * "trainedAlgorithmicMedia", generator names, Stable-Diffusion PNG text). It
 * catches images saved straight from such a tool; a screenshot or a re-saved
 * copy carries no markers and will pass.
 *
 * Independent of Laravel on purpose (plain PHP + GD), so it is easy to test.
 */
final class ProfilePhotoInspector
{
    /** Lower-case strings that mark an image as AI-generated. Keep in sync with photoCheck.js. */
    public const AI_MARKERS = [
        'trainedalgorithmicmedia',
        'compositewithtrainedalgorithmicmedia',
        'algorithmicmedia',
        'midjourney',
        'dall-e', 'dall·e', 'dalle',
        'openai',
        'chatgpt',
        'stable diffusion', 'stablediffusion',
        'comfyui', 'automatic1111', 'invokeai',
        'adobe firefly',
        'synthid',
        'leonardo.ai',
        'ideogram',
        'negative prompt',
        'sampler:',
        'ai generated', 'ai-generated', 'generated by ai', 'made with ai',
        'made with google ai', 'imagen', 'bing image creator', 'nightcafe', 'dreamstudio', 'playground ai',
    ];

    /** Lower-case names of retouching apps / editors that leave a trace in the file. Keep in sync with photoCheck.js. */
    public const EDIT_MARKERS = [
        'adobe photoshop', 'generative fill', 'generative expand',
        'faceapp', 'facetune', 'remini', 'lensa', 'meitu', 'youcam', 'beautyplus', 'beauty plus',
        'b612', 'airbrush', 'picsart', 'snapseed', 'pixlr', 'fotor', 'photoroom', 'canva',
    ];

    /**
     * @param  array{min_side?:int,min_sharpness?:float,bg_min_fraction?:float,max_pixels?:int}  $opt
     * @return list<array{code:string,message:string}>  empty list = photo is acceptable
     */
    public static function inspect(string $path, array $opt = []): array
    {
        $minSide = $opt['min_side'] ?? 300;
        $minSharp = $opt['min_sharpness'] ?? 40.0;
        $bgMin = $opt['bg_min_fraction'] ?? 0.6;
        $maxPixels = $opt['max_pixels'] ?? 25000000;

        $info = @getimagesize($path);
        if ($info === false || ! in_array($info[2] ?? 0, [IMAGETYPE_JPEG, IMAGETYPE_PNG, IMAGETYPE_WEBP], true)) {
            return [self::problem('type', 'Use a JPG, PNG or WebP photo.')];
        }

        [$w, $h] = $info;
        if (min($w, $h) < $minSide) {
            return [self::problem('resolution', "This photo is too small. Use a clear photo that is at least {$minSide}px on its shortest side.")];
        }

        if (self::aiMarkers($path) !== []) {
            return [self::problem('ai', 'This image is tagged as AI-generated. Please upload a real photo of yourself.')];
        }
        if (self::editMarkers($path) !== []) {
            return [self::problem('edited', 'This photo was edited or retouched in an app. Please upload the original photo straight from your camera.')];
        }

        // Pixel checks need GD; without it (or for huge images) the browser's
        // checks and the staff review are what remain.
        if (! function_exists('imagecreatefromstring') || ($w * $h) > $maxPixels) {
            return [];
        }

        $raw = @file_get_contents($path);
        $img = $raw === false ? false : @imagecreatefromstring($raw);
        if ($img === false) {
            return [self::problem('unreadable', 'This file could not be read as an image. Choose another photo.')];
        }
        $img = self::upright($img, $path, (int) $info[2]);

        $problems = [];
        $small = self::scaled($img, 640);

        // A cut-out photo (background removed) stores see-through pixels as black, so
        // it would otherwise be reported as a dark background. Say what is really wrong.
        if (self::transparentFraction($img) >= 0.5) {
            $problems[] = self::problem('transparent', 'This photo has a transparent (removed) background, so it was edited. Use the original photo, taken in front of a plain white or light wall.');
        } elseif (self::backgroundFraction($small) < $bgMin) {
            $problems[] = self::problem('background', 'Use a plain white or very light background with nothing else in the picture.');
        }

        if (self::sharpness($small) < $minSharp) {
            $problems[] = self::problem('blurry', 'This photo is blurry. Use a sharp, in-focus photo in good light.');
        }

        return $problems;
    }

    /** @return list<string> markers found in the first MB of the file */
    public static function aiMarkers(string $path): array
    {
        $head = @file_get_contents($path, false, null, 0, 1048576);
        if ($head === false || $head === '') {
            return [];
        }
        $text = strtolower($head);

        return array_values(array_filter(self::AI_MARKERS, fn ($m) => str_contains($text, $m)));
    }

    /** @return list<string> editing tools named in the first MB of the file */
    public static function editMarkers(string $path): array
    {
        $head = @file_get_contents($path, false, null, 0, 1048576);
        if ($head === false || $head === '') {
            return [];
        }
        $text = strtolower($head);

        return array_values(array_filter(self::EDIT_MARKERS, fn ($m) => str_contains($text, $m)));
    }

    /** Fraction (0-1) of the top/side edge pixels that are light and colourless. */
    public static function backgroundFraction(\GdImage $img): float
    {
        $w = imagesx($img);
        $h = imagesy($img);
        $bandX = (int) round($w * 0.14);
        $bandTop = (int) round($h * 0.08);
        $halfH = (int) round($h * 0.55);
        $total = 0;
        $plain = 0;

        for ($y = 0; $y < $halfH; $y += 2) {
            for ($x = 0; $x < $w; $x += 2) {
                if ($y >= $bandTop && $x >= $bandX && $x < $w - $bandX) {
                    continue;
                }
                $rgb = imagecolorat($img, $x, $y);
                $r = ($rgb >> 16) & 255;
                $g = ($rgb >> 8) & 255;
                $b = $rgb & 255;
                $lum = 0.299 * $r + 0.587 * $g + 0.114 * $b;
                $chroma = max($r, $g, $b) - min($r, $g, $b);
                $total++;
                if ($lum >= 185 && $chroma <= 30) {
                    $plain++;
                }
            }
        }

        return $total ? $plain / $total : 0.0;
    }

    /** Fraction (0-1) of the top/side edge pixels that are see-through (PNG / WebP with the background removed). */
    public static function transparentFraction(\GdImage $img): float
    {
        $w = imagesx($img);
        $h = imagesy($img);
        $step = max(2, (int) round(max($w, $h) / 320));
        $bandX = (int) round($w * 0.14);
        $bandTop = (int) round($h * 0.08);
        $halfH = (int) round($h * 0.55);
        $total = 0;
        $clear = 0;

        for ($y = 0; $y < $halfH; $y += $step) {
            for ($x = 0; $x < $w; $x += $step) {
                if ($y >= $bandTop && $x >= $bandX && $x < $w - $bandX) {
                    continue;
                }
                $total++;
                // GD alpha runs 0 (opaque) to 127 (fully transparent)
                if ((((imagecolorat($img, $x, $y)) >> 24) & 127) >= 64) {
                    $clear++;
                }
            }
        }

        return $total ? $clear / $total : 0.0;
    }

    /** Variance of the 3x3 Laplacian of the central region, measured at 192px. */
    public static function sharpness(\GdImage $img): float
    {
        $w = imagesx($img);
        $h = imagesy($img);
        $crop = imagecrop($img, [
            'x' => (int) round($w * 0.25), 'y' => (int) round($h * 0.20),
            'width' => max(1, (int) round($w * 0.5)), 'height' => max(1, (int) round($h * 0.55)),
        ]);
        if ($crop === false) {
            return 0.0;
        }
        $sq = imagescale($crop, 192, 192, IMG_BICUBIC);
        if ($sq === false) {
            return 0.0;
        }

        $g = [];
        for ($y = 0; $y < 192; $y++) {
            for ($x = 0; $x < 192; $x++) {
                $rgb = imagecolorat($sq, $x, $y);
                $g[$y][$x] = 0.299 * (($rgb >> 16) & 255) + 0.587 * (($rgb >> 8) & 255) + 0.114 * ($rgb & 255);
            }
        }
        $sum = 0.0;
        $sumSq = 0.0;
        $n = 0;
        for ($y = 1; $y < 191; $y++) {
            for ($x = 1; $x < 191; $x++) {
                $v = $g[$y - 1][$x] + $g[$y + 1][$x] + $g[$y][$x - 1] + $g[$y][$x + 1] - 4 * $g[$y][$x];
                $sum += $v;
                $sumSq += $v * $v;
                $n++;
            }
        }
        $mean = $sum / $n;

        return $sumSq / $n - $mean * $mean;
    }

    private static function scaled(\GdImage $img, int $maxSide): \GdImage
    {
        $w = imagesx($img);
        $h = imagesy($img);
        if (max($w, $h) <= $maxSide) {
            return $img;
        }
        $s = imagescale($img, $w >= $h ? $maxSide : (int) round($w * $maxSide / $h), $w >= $h ? (int) round($h * $maxSide / $w) : $maxSide, IMG_BICUBIC);

        return $s === false ? $img : $s;
    }

    /** Phones store sideways pictures with an EXIF flag; GD ignores it, so apply it. */
    private static function upright(\GdImage $img, string $path, int $type): \GdImage
    {
        if ($type !== IMAGETYPE_JPEG || ! function_exists('exif_read_data')) {
            return $img;
        }
        $exif = @exif_read_data($path);
        $angle = match ((int) ($exif['Orientation'] ?? 1)) {
            3 => 180, 6 => -90, 8 => 90, default => 0,
        };
        if ($angle === 0) {
            return $img;
        }
        $rot = imagerotate($img, $angle, 0xFFFFFF);

        return $rot === false ? $img : $rot;
    }

    /** @return array{code:string,message:string} */
    private static function problem(string $code, string $message): array
    {
        return ['code' => $code, 'message' => $message];
    }
}
