/** Latin-1 decode of the first part of the file, where metadata lives. */
export function bytesToSearchText(bytes, limit = 1024 * 1024) {
    const n = Math.min(bytes.length, limit);
    let out = '';
    const CHUNK = 8192;
    for (let i = 0; i < n; i += CHUNK) {
        out += String.fromCharCode.apply(null, bytes.subarray(i, Math.min(n, i + CHUNK)));
    }
    return out.toLowerCase();
}

/** → array of AI markers found in the file's metadata (empty = none found). */
export function scanForAiMarkers(bytes) {
    const text = bytesToSearchText(bytes);
    return AI_MARKERS.filter((m) => text.includes(m));
}

/** → array of editing / retouching tools named in the file's metadata. */
export function scanForEditMarkers(bytes) {
    const text = bytesToSearchText(bytes);
    return EDIT_MARKERS.filter((m) => text.includes(m));
}

/* ───────────────────────────── Pixel helpers ───────────────────────────── */

/** RGBA → luminance (0-255) array. */
export function toGray({ data, width, height }) {
    const g = new Float32Array(width * height);
    for (let i = 0, p = 0; p < g.length; i += 4, p += 1) {
        g[p] = 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
    }
    return { data: g, width, height };
}

/** Area-average resize of a gray image (stable regardless of source size). */
export function resizeGray(gray, tw, th) {
    const { data, width: sw, height: sh } = gray;
    const out = new Float32Array(tw * th);
    for (let y = 0; y < th; y += 1) {
        const y0 = Math.floor((y * sh) / th);
        const y1 = Math.max(y0 + 1, Math.floor(((y + 1) * sh) / th));
        for (let x = 0; x < tw; x += 1) {
            const x0 = Math.floor((x * sw) / tw);
            const x1 = Math.max(x0 + 1, Math.floor(((x + 1) * sw) / tw));
            let sum = 0; let cnt = 0;
            for (let yy = y0; yy < y1; yy += 1) {
                for (let xx = x0; xx < x1; xx += 1) { sum += data[yy * sw + xx]; cnt += 1; }
            }
            out[y * tw + x] = sum / cnt;
        }
    }
    return { data: out, width: tw, height: th };
}

export function cropGray(gray, x, y, w, h) {
    const x0 = Math.max(0, Math.round(x)); const y0 = Math.max(0, Math.round(y));
    const x1 = Math.min(gray.width, Math.round(x + w)); const y1 = Math.min(gray.height, Math.round(y + h));
    const cw = Math.max(1, x1 - x0); const ch = Math.max(1, y1 - y0);
    const out = new Float32Array(cw * ch);
    for (let yy = 0; yy < ch; yy += 1) {
        for (let xx = 0; xx < cw; xx += 1) out[yy * cw + xx] = gray.data[(y0 + yy) * gray.width + (x0 + xx)];
    }
    return { data: out, width: cw, height: ch };
}

/** Variance of the 3×3 Laplacian — low = blurry, high = sharp detail. */
export function laplacianVariance(gray) {
    const { data, width: w, height: h } = gray;
    let sum = 0; let sumSq = 0; let n = 0;
    for (let y = 1; y < h - 1; y += 1) {
        for (let x = 1; x < w - 1; x += 1) {
            const i = y * w + x;
            const v = data[i - w] + data[i + w] + data[i - 1] + data[i + 1] - 4 * data[i];
            sum += v; sumSq += v * v; n += 1;
        }
    }
    if (!n) return 0;
    const mean = sum / n;
    return sumSq / n - mean * mean;
}

/** Sharpness of the face, measured at a fixed 192px so image size doesn't matter. */
export function faceSharpness(gray, box) {
    const padX = box.width * 0.1; const padY = box.height * 0.1;
    const crop = cropGray(gray, box.x - padX, box.y - padY, box.width + padX * 2, box.height + padY * 2);
    return laplacianVariance(resizeGray(crop, 192, 192));
}

export function faceLighting(gray, box) {
    const crop = cropGray(gray, box.x + box.width * 0.2, box.y + box.height * 0.2, box.width * 0.6, box.height * 0.6);
    let sum = 0; let sumSq = 0;
    for (let i = 0; i < crop.data.length; i += 1) { sum += crop.data[i]; sumSq += crop.data[i] * crop.data[i]; }
    const n = crop.data.length || 1;
    const mean = sum / n;
    return { mean, contrast: Math.sqrt(Math.max(0, sumSq / n - mean * mean)) };
}

/**
 * Looks at the edges of the picture above the shoulders (top band + left/right
 * bands of the upper half), where a formal photo shows only plain backdrop.
 * Returns how much of it is plain, light and colourless.
 */
export function backgroundStats({ data, width: w, height: h }) {
    const bandX = Math.round(w * 0.14);
    const bandTop = Math.round(h * 0.08);
    const halfH = Math.round(h * 0.55);
    let total = 0; let plain = 0; let lumSum = 0; let chromaSum = 0; let busy = 0; let see = 0;
    const lumAt = (x, y) => {
        const i = (Math.min(h - 1, y) * w + Math.min(w - 1, x)) * 4;
        return 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
    };
    const visit = (x, y) => {
        const i = (y * w + x) * 4;
        const r = data[i]; const g = data[i + 1]; const b = data[i + 2];
        const lum = 0.299 * r + 0.587 * g + 0.114 * b;
        const chroma = Math.max(r, g, b) - Math.min(r, g, b);
        total += 1; lumSum += lum; chromaSum += chroma;
        // a see-through pixel stores r,g,b = 0 (black): count it separately so it is not mistaken for a dark wall
        if (data[i + 3] < 200) see += 1;
        if (lum >= PHOTO_RULES.bgMinLum && chroma <= PHOTO_RULES.bgMaxChroma) plain += 1;
        // strong local edge = something is hanging / standing behind the person
        if (Math.abs(lumAt(x + 2, y) - lum) + Math.abs(lumAt(x, y + 2) - lum) > 40) busy += 1;
    };
    for (let y = 0; y < halfH; y += 2) {
        for (let x = 0; x < w; x += 2) {
            if (y < bandTop || x < bandX || x >= w - bandX) visit(x, y);
        }
    }
    return {
        fraction: total ? plain / total : 0,
        busy: total ? busy / total : 0,
        meanLum: total ? lumSum / total : 0,
        meanChroma: total ? chromaSum / total : 0,
        transparent: total ? see / total : 0,
    };
}

/* ─────────────────────────── Face geometry rules ─────────────────────────── */

/** Tells the person which way to move, as they see themselves in the photo. */
function framingAdvice(cx, cy, inside, headroom) {
    const R = PHOTO_RULES;
    const tips = [];
    if (cx > R.centerX[1]) tips.push('Your face is too far to the right of the photo. Move left so you are in the middle.');
    else if (cx < R.centerX[0]) tips.push('Your face is too far to the left of the photo. Move right so you are in the middle.');
    if (cy < R.centerY[0] || headroom < R.minHeadroom) tips.push('Your head is too high. Leave a little space above your head.');
    else if (cy > R.centerY[1]) tips.push('Your face is too low. Raise the camera so your face sits in the upper-middle of the photo.');
    if (!inside && !tips.length) tips.push('Part of your head is cut off. Keep your whole head and shoulders in view.');
    return tips.join(' ') || 'Centre your face in the picture and keep your whole head and shoulders in view.';
}

const dist = (a, b) => Math.hypot(a.x - b.x, a.y - b.y);
const eyeOpenness = (p, s) => (dist(p[s + 1], p[s + 5]) + dist(p[s + 2], p[s + 4])) / (2 * dist(p[s], p[s + 3]) || 1);

/**
 * detection = { score, box: {x,y,width,height}, points: 68 landmark {x,y} }
 * in the coordinates of a W×H image. Returns the face-related checks.
 */
export function evaluateFace(detection, W, H) {
    const R = PHOTO_RULES;
    const { box, points } = detection;
    const cx = (box.x + box.width / 2) / W;
    const cy = (box.y + box.height / 2) / H;
    const wr = box.width / W;
    const inside = box.x >= W * R.edgeMargin && box.y >= H * R.edgeMargin
        && box.x + box.width <= W * (1 - R.edgeMargin) && box.y + box.height <= H * (1 - R.edgeMargin);

    const nose = points[30]; const j0 = points[0]; const j16 = points[16];
    const yaw = (nose.x - j0.x) / ((j16.x - j0.x) || 1);
    const le = points.slice(36, 42); const re = points.slice(42, 48);
    const lc = { x: le.reduce((s, p) => s + p.x, 0) / 6, y: le.reduce((s, p) => s + p.y, 0) / 6 };
    const rc = { x: re.reduce((s, p) => s + p.x, 0) / 6, y: re.reduce((s, p) => s + p.y, 0) / 6 };
    const roll = Math.abs((Math.atan2(rc.y - lc.y, rc.x - lc.x) * 180) / Math.PI);
    const eyes = Math.min(eyeOpenness(points, 36), eyeOpenness(points, 42));

    return [
        {
            id: 'framing',
            label: 'Face is centred in the frame',
            pass: inside && cx >= R.centerX[0] && cx <= R.centerX[1]
                && cy >= R.centerY[0] && cy <= R.centerY[1] && box.y >= H * R.minHeadroom,
            fix: framingAdvice(cx, cy, inside, box.y / H),
            value: { cx, cy },
        },
        {
            id: 'size',
            label: 'Face fills the right amount of the photo',
            pass: wr >= R.faceWidthRatio[0] && wr <= R.faceWidthRatio[1],
            fix: wr < R.faceWidthRatio[0]
                ? 'Your face is too small or far away. Move closer so head and shoulders fill the frame.'
                : 'Your face is too close. Step back so your head and shoulders fit the frame.',
            value: wr,
        },
        {
            id: 'pose',
            label: 'Looking straight at the camera',
            pass: yaw >= R.yaw[0] && yaw <= R.yaw[1] && roll <= R.maxRollDeg,
            fix: 'Face the camera directly, with your head level (not turned or tilted).',
            value: { yaw, roll },
        },
        {
            id: 'eyes',
            label: 'Eyes open and visible',
            pass: eyes >= R.minEyeOpen,
            fix: 'Keep both eyes open and uncovered (no sunglasses, hair or hands over your eyes).',
            value: eyes,
        },
    ];
}


/* ───────────────── Cap / hat and held-object heuristics ───────────────── */

const ycc = (r, g, b) => ({
    y: 0.299 * r + 0.587 * g + 0.114 * b,
    cb: 128 - 0.168736 * r - 0.331264 * g + 0.5 * b,
    cr: 128 + 0.5 * r - 0.418688 * g - 0.081312 * b,
});
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.floor(s.length / 2)] : 0; };
const mid = (a, b) => ({ x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 });

/**
 * This person's own skin colour, sampled from the cheeks and nose bridge, so
 * the test works for every skin tone and lighting. null if it can't be read.
 */
export function sampleSkin({ data, width: w, height: h }, points, faceW) {
    const spots = [mid(points[3], points[31]), mid(points[13], points[35]), points[28]];
    const r = Math.max(2, Math.round(faceW * 0.05));
    const Y = []; const CB = []; const CR = [];
    for (const c of spots) {
        for (let dy = -r; dy <= r; dy += 1) {
            for (let dx = -r; dx <= r; dx += 1) {
                const x = Math.round(c.x + dx); const y = Math.round(c.y + dy);
                if (x < 0 || y < 0 || x >= w || y >= h) continue;
                const i = (y * w + x) * 4;
                const v = ycc(data[i], data[i + 1], data[i + 2]);
                Y.push(v.y); CB.push(v.cb); CR.push(v.cr);
            }
        }
    }
    if (Y.length < 20) return null;
    return { y: median(Y), cb: median(CB), cr: median(CR) };
}

const looksLikeSkin = (r, g, b, ref) => {
    const v = ycc(r, g, b);
    return Math.abs(v.cb - ref.cb) <= 14 && Math.abs(v.cr - ref.cr) <= 14
        && v.y >= ref.y * 0.4 && v.y <= ref.y * 1.55;
};

/**
 * Cap / hat / headband: the strip of forehead just above the eyebrows should be
 * skin. A cap (or a full fringe) replaces it with dark or coloured fabric.
 */
export function evaluateHeadwear(imageData, points, box) {
    const R = PHOTO_RULES;
    const { data, width: w, height: h } = imageData;
    const skin = sampleSkin(imageData, points, box.width);
    const result = (pass, value) => ({
        id: 'headwear',
        label: 'Forehead visible (no cap, hat or headband)',
        pass,
        fix: 'Your forehead is covered. Take off any cap, hat or headband, and move hair away from your forehead.',
        value,
    });
    if (!skin) return result(true, null);

    const browTop = Math.min(...points.slice(17, 27).map((p) => p.y));
    const eyeY = (points[36].y + points[45].y) / 2;
    const span = Math.max(1, points[8].y - eyeY);          // eyes → chin
    const x0 = Math.round(points[19].x); const x1 = Math.round(points[24].x);
    const y0 = Math.round(browTop - span * 0.34); const y1 = Math.round(browTop - span * 0.06);
    let total = 0; let skinPx = 0;
    for (let y = Math.max(0, y0); y <= Math.min(h - 1, y1); y += 1) {
        for (let x = Math.max(0, x0); x <= Math.min(w - 1, x1); x += 1) {
            const i = (y * w + x) * 4;
            total += 1;
            if (looksLikeSkin(data[i], data[i + 1], data[i + 2], skin)) skinPx += 1;
        }
    }
    // no strip to look at (head touches the top edge) → the framing check reports it
    if (total < 30) return result(true, null);
    const fraction = skinPx / total;
    return result(fraction >= R.foreheadMinSkin, fraction);
}

/**
 * Something held in front of the body — an ID card, paper, phone, a raised hand.
 * Looks below the chin: skin outside the neck column (hands / arms), and bright
 * blocks full of printed detail (a card or paper; plain white clothing is smooth
 * and does not count).
 */
export function evaluateHeldObjects(imageData, points, box) {
    const R = PHOTO_RULES;
    const { data, width: w, height: h } = imageData;
    const skin = sampleSkin(imageData, points, box.width);
    const chin = points[8].y;
    const top = Math.round(chin + box.height * 0.12);
    const neckL = points[5].x; const neckR = points[11].x;
    const result = (pass, value) => ({
        id: 'held',
        label: 'Nothing held up in front of you',
        pass,
        fix: 'Something is in front of you (an ID card, paper, phone or your hand). Put it down and keep both hands out of the picture.',
        value,
    });
    if (top >= h - 8) return result(true, null);

    // Only the middle of the lower frame counts: a hand or phone held up sits in
    // front of the chest, while arms at the bottom corners are just part of the pose.
    const sx0 = Math.round(w * R.heldSideMargin); const sx1 = w - sx0;
    const yEnd = Math.round(h * (1 - R.heldBottomMargin));
    let total = 0; let skinPx = 0;
    for (let y = top; y < yEnd; y += 2) {
        for (let x = sx0; x < sx1; x += 2) {
            total += 1;
            if (!skin || (x >= neckL && x <= neckR)) continue;
            const i = (y * w + x) * 4;
            if (looksLikeSkin(data[i], data[i + 1], data[i + 2], skin)) skinPx += 1;
        }
    }
    const skinFraction = total ? skinPx / total : 0;

    // 12px blocks that are bright, not coloured, and full of fine edges (printed
    // text, photos, logos). A single step edge (shoulder against wall) or smooth
    // white clothing does not count.
    const B = 12; let blocks = 0; let card = 0;
    const lumAt = (x, y) => { const i = (y * w + x) * 4; return 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2]; };
    for (let by = top; by + B <= h; by += B) {
        for (let bx = 0; bx + B <= w; bx += B) {
            let sum = 0; let chroma = 0; let n = 0; let edges = 0; let pairs = 0;
            for (let y = by; y < by + B; y += 2) {
                for (let x = bx; x < bx + B; x += 2) {
                    const i = (y * w + x) * 4;
                    const l = lumAt(x, y);
                    sum += l; n += 1;
                    chroma += Math.max(data[i], data[i + 1], data[i + 2]) - Math.min(data[i], data[i + 1], data[i + 2]);
                    if (x + 2 < bx + B) { pairs += 1; if (Math.abs(lumAt(x + 2, y) - l) > 28) edges += 1; }
                    if (y + 2 < by + B) { pairs += 1; if (Math.abs(lumAt(x, y + 2) - l) > 28) edges += 1; }
                }
            }
            blocks += 1;
            if (sum / n > 150 && chroma / n < 55 && edges / pairs > 0.3) card += 1;
        }
    }
    const cardFraction = blocks ? card / blocks : 0;
    return result(skinFraction <= R.heldMaxSkin && cardFraction <= R.heldMaxCardBlocks, { skin: skinFraction, card: cardFraction });
}

/** Quality checks that need only pixels + the face box. */
export function evaluatePixels(imageData, box, points = null) {
    const R = PHOTO_RULES;
    const gray = toGray(imageData);
    const sharp = faceSharpness(gray, box);
    const light = faceLighting(gray, box);
    const bg = backgroundStats(imageData);
    const seeThrough = !R.allowTransparentBg && bg.transparent >= R.transparentBgMin;
    const extra = points ? [evaluateHeadwear(imageData, points, box), evaluateHeldObjects(imageData, points, box)] : [];
    return [
        {
            id: 'sharp',
            label: 'Sharp and in focus (not blurry)',
            pass: sharp >= R.minSharpness,
            fix: 'The photo is blurry. Hold the camera steady, wipe the lens and use good light.',
            value: sharp,
        },
        {
            id: 'light',
            label: 'Evenly lit (not too dark or washed out)',
            pass: light.mean >= R.faceLum[0] && light.mean <= R.faceLum[1] && light.contrast >= R.minFaceContrast,
            fix: light.mean < R.faceLum[0]
                ? 'Your face is too dark. Face a window or a light so it is evenly lit.'
                : 'Your face is washed out or too flat. Avoid harsh glare or strong backlight.',
            value: light,
        },
        {
            id: 'background',
            label: 'Plain white / light background',
            pass: !seeThrough && bg.fraction >= R.bgMinFraction && bg.busy <= R.bgMaxBusy,
            fix: seeThrough
                ? 'This photo has a transparent (removed) background, so it was edited. Use the original photo, taken in front of a plain white or light wall.'
                : bg.busy > R.bgMaxBusy && bg.fraction >= R.bgMinFraction
                    ? 'Something is hanging or standing behind you (a frame, door, poster or shelf). Stand in front of a bare wall.'
                    : 'Use a plain white or very light wall behind you, with nothing else in the picture.',
            value: bg,
        },
        ...extra,
    ];
}

