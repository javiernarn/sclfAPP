const loadImage = (file) => new Promise((resolve, reject) => {
    const url = URL.createObjectURL(file);
    const img = new Image();
    img.onload = () => { URL.revokeObjectURL(url); resolve(img); };
    img.onerror = () => { URL.revokeObjectURL(url); reject(new Error('unreadable')); };
    img.src = url;
});

/**
 * Phone cameras make 5–15 MB photos. Rather than refuse them, re-save a smaller
 * JPEG (longest side `shrinkTo`, quality stepped down until it is under the
 * limit). The AI / edit tags are read from the ORIGINAL file before this runs.
 */
export async function shrinkImage(img, file, R) {
    const scale = Math.min(1, R.shrinkTo / Math.max(img.naturalWidth, img.naturalHeight));
    const c = document.createElement('canvas');
    c.width = Math.round(img.naturalWidth * scale); c.height = Math.round(img.naturalHeight * scale);
    c.getContext('2d').drawImage(img, 0, 0, c.width, c.height);
    const base = (file.name || 'photo').replace(/\.[^.]+$/, '');
    for (const q of [0.9, 0.8, 0.7, 0.6]) {
        // eslint-disable-next-line no-await-in-loop
        const blob = await new Promise((resolve) => { c.toBlob(resolve, 'image/jpeg', q); });
        if (blob && blob.size <= R.maxBytes) return new File([blob], `${base}.jpg`, { type: 'image/jpeg' });
    }
    throw new Error('too-big');
}

const fail = (id, label, fix) => ({ id, label, pass: false, fix });
const ok = (id, label) => ({ id, label, pass: true });

/**
 * Runs every check on `file`. `onStep(id)` is called as each stage starts so
 * the UI can show progress. Resolves { ok, checks, previewUrl? } — never throws.
 * `checks` is a list of { id, label, pass, fix? }; `ok` is true only if all pass.
 * `file` is the photo to use when `ok` (a smaller JPEG copy if the original was big).
 * `face` is { W, H, box } (analysis-image coordinates) when exactly one face was found.
 */
export async function checkProfilePhoto(file, onStep = () => {}) {
    const R = PHOTO_RULES;
    const checks = [];
    let face = null; // { W, H, box } of the one face found, so the pop-up can draw where it is
    let finalFile = file; // the photo to use: the original, or a smaller copy of a big phone photo
    const done = () => { const okAll = checks.every((c) => c.pass); return { ok: okAll, checks, face, file: okAll ? finalFile : null }; };

    // Photo check switched off in .env (VITE_PHOTO_CHECK_ENABLED=false): accept the file as is.
    if (!PHOTO_CHECK_ENABLED) {
        if (!/^image\/(jpeg|png|webp)$/.test(file.type)) {
            checks.push(fail('type', 'JPG, PNG or WebP image', 'Choose a JPG, PNG or WebP photo.'));
            return done();
        }
        return { ok: true, checks, face: null, file, skipped: true };
    }

    // 1. The file itself
    onStep('file');
    if (!/^image\/(jpeg|png|webp)$/.test(file.type)) {
        checks.push(fail('type', 'JPG, PNG or WebP image', 'Choose a JPG, PNG or WebP photo (not a GIF, screenshot document or other file).'));
        return done();
    }
    if (file.size > R.hardMaxBytes) {
        checks.push(fail('bytes', 'Smaller than 40 MB', 'This file is far too large to be a normal photo. Choose a different one.'));
        return done();
    }
    let img;
    try { img = await loadImage(file); } catch {
        checks.push(fail('readable', 'Readable image', 'This file could not be opened as an image. Choose another photo.'));
        return done();
    }
    const side = Math.min(img.naturalWidth, img.naturalHeight);
    if (side < R.minSide) {
        checks.push(fail('resolution', `At least ${R.minSide}px on the shortest side`, `This photo is only ${side}px wide. Use a larger, higher-quality photo (at least ${R.minSide}px).`));
        return done();
    }
    checks.push(ok('resolution', `Good size (${img.naturalWidth}×${img.naturalHeight})`));

    // 2. AI markers in the file's metadata
    onStep('ai');
    try {
        const head = new Uint8Array(await file.slice(0, 1024 * 1024).arrayBuffer());
        if (scanForAiMarkers(head).length) {
            checks.push(fail('ai', 'Real photo, not AI-generated', 'This image is tagged as AI-generated. Please upload a real photo of yourself.'));
        } else if (scanForEditMarkers(head).length) {
            checks.push(fail('edited', 'Original photo, not retouched', 'This photo was edited or retouched in an app. Please upload the original photo straight from your camera.'));
        } else {
            checks.push(ok('ai', 'No AI or editing tags in the file'));
        }
    } catch {
        checks.push(ok('ai', 'No AI or editing tags in the file'));
    }
    if (checks.some((c) => !c.pass)) return done();

    // Big phone photo → shrink it (after the tags above were read from the original)
    if (file.size > R.maxBytes || Math.max(img.naturalWidth, img.naturalHeight) > R.shrinkTo * 1.5) {
        try { finalFile = await shrinkImage(img, file, R); } catch {
            checks.push(fail('bytes', 'Smaller than 5 MB', 'This photo is too large and could not be made smaller. Choose a different photo.'));
            return done();
        }
    }

    // 3. Face
    onStep('face');
    const scale = Math.min(1, R.analysisMaxSide / Math.max(img.naturalWidth, img.naturalHeight));
    const W = Math.round(img.naturalWidth * scale); const H = Math.round(img.naturalHeight * scale);
    const canvas = document.createElement('canvas');
    canvas.width = W; canvas.height = H;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    if (R.allowTransparentBg) { ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, W, H); }
    ctx.drawImage(img, 0, 0, W, H);

    let faces;
    try { faces = await detectFaces(canvas); } catch {
        checks.push(fail('detector', 'Face check available', 'The face check could not start. Check your connection and try again.'));
        return done();
    }
    const strong = faces.filter((f) => f.score >= R.minFaceScore);
    if (strong.length === 0) {
        checks.push(fail('face', 'One clear face', 'No clear face was found. Face the camera in good light with nothing covering your face.'));
        return done();
    }
    if (strong.length > 1) {
        checks.push(fail('face', 'Only one person in the photo', 'More than one face was found. The photo must show only you.'));
        return done();
    }
    checks.push(ok('face', 'One clear face'));
    face = { W, H, box: strong[0].box };
    checks.push(...evaluateFace(strong[0], W, H));

    // 4. Quality + background
    onStep('quality');
    checks.push(...evaluatePixels(ctx.getImageData(0, 0, W, H), strong[0].box, strong[0].points));

    // Optional (VITE_PHOTO_CHECK_CONSOLE=true): shows the measured numbers behind each check
    // in the browser console, so a surprising rejection can be traced to the threshold that tripped.
    if (PHOTO_CHECK_CONSOLE) {
        // eslint-disable-next-line no-console
        console.table(checks.map((c) => ({ id: c.id, pass: c.pass, value: JSON.stringify(c.value ?? null) })));
    }

    return done();
}
