/**
 * photoCheck.js — checks a profile photo before it is accepted.
 *
 * The photo must look like a formal ID-style picture: one clearly visible,
 * front-facing face, centred, on a plain light background, sharp and well lit.
 * Everything runs in the visitor's browser (the photo is not sent anywhere
 * just to be checked), and the server repeats the checks that don't need face
 * detection (see App\Support\ProfilePhotoInspector).
 *
 * What this can and cannot do — kept honest on purpose:
 *   - Face detection / pose / blur / lighting / background: real, measured checks.
 *   - "Is it AI-generated?": there is no reliable way to tell from pixels alone.
 *     This looks for the markers AI tools write into the file (IPTC
 *     "trainedAlgorithmicMedia", generator names, Stable-Diffusion PNG text).
 *     It catches images saved straight from an AI tool; a screenshot or a
 *     re-saved copy carries no markers and will pass.
 *   - Caps / hats and things held up to the camera (an ID card, a phone) are
 *     found with colour + position heuristics around the face landmarks, not a
 *     trained object detector, so they catch the obvious cases (a cap over the
 *     forehead, a hand and card in front of the body) but not every one.
 *   - "Casual vs formal clothing" cannot be judged by a machine; the plain
 *     background / framing rules and the staff review cover it.
 *
 * The pure functions below take plain data (RGBA arrays, landmark points) so
 * they can be unit-tested outside a browser.
 */

export const PHOTO_RULES = {
    maxBytes: 5 * 1024 * 1024,        // size of the photo that is finally used
    hardMaxBytes: 40 * 1024 * 1024,   // bigger originals are refused outright (memory)
    shrinkTo: 2048,                   // px, longest side after shrinking a big phone photo
    minSide: 400,              // px, shorter side of the original
    analysisMaxSide: 640,      // px, image is scaled to this for analysis
    minFaceScore: 0.6,
    faceWidthRatio: [0.26, 0.58],   // face box width / image width
    centerX: [0.42, 0.58],          // face centre, fraction of width  (0.5 = dead centre)
    centerY: [0.28, 0.62],          // face centre, fraction of height (head-and-shoulders framing)
    minHeadroom: 0.05,              // gap above the face box, fraction of height
    edgeMargin: 0.015,              // face box must not touch the edges
    yaw: [0.35, 0.65],              // nose position between jaw ends (0.5 = straight)
    maxRollDeg: 12,
    minEyeOpen: 0.1,                // eye aspect ratio
    minSharpness: 40,               // Laplacian variance of the face at 192px
    faceLum: [55, 238],
    minFaceContrast: 16,
    bgMinLum: 185,
    bgMaxChroma: 30,
    bgMinFraction: 0.8,             // share of background pixels that look plain light
    transparentBgMin: 0.5,          // share of edge pixels that are see-through (background removed) before the photo is refused
    allowTransparentBg: false,      // true = paint see-through areas white and accept cut-out photos; false = refuse them (they are edited)
    bgMaxBusy: 0.12,                // share of background pixels with strong edges (posters, doors, frames)
    foreheadMinSkin: 0.3,           // share of the forehead strip that must look like skin (cap / hat check)
    heldMaxSkin: 0.07,              // skin outside the neck, below the chin (hands, arms in front of the body)
    heldSideMargin: 0.15,           // ignore the outer 15% on each side when looking for skin (upper arms / sleeves at the frame edge)
    heldBottomMargin: 0.15,         // ignore the bottom 15% (forearms or elbows entering the frame from below are normal)
    heldMaxCardBlocks: 0.05,        // bright blocks with printed detail below the chin (ID card, paper, phone)
};

